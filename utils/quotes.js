function hashString(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

function getDailyQuote(dateStr) {
  const idx = hashString(dateStr) % QUOTES.length;
  return QUOTES[idx];
}

